--Find total customers by countries
SELECT
country,
COUNT(customer_key) AS total_customers
FROM GOLD.dim_customers
GROUP BY COUNTRY
ORDER BY total_customers DESC

--Find total customers by gender
Select 
gender,
COUNT(customer_key) AS total_cutomers_by_gender
from gold.dim_customers
GROUP BY gender
ORDER BY total_cutomers_by_gender DESC

--Find Total products by category
SELECT
category,
COUNT(PRODUCT_KEY) AS total_products
FROM GOLD.dim_products
GROUP BY category
ORDER BY total_products DESC

--What is the average costs in each country
SELECT
category,
AVG(cost) AS avg_cost
FROM GOLD.dim_products
GROUP BY category
ORDER BY avg_cost DESC

--What is the total revenue generated for each category
SELECT
p.category,
SUM(f.sales_amount) total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p 
ON p.product_key = f.product_key
GROUP BY P.category 
ORDER BY total_revenue DESC


--Find total revenue generated by each customer

SELECT 
c.first_name,
c.last_name,
c.customer_key,
SUM(f.sales_amount) total_rev
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name
ORDER BY total_rev DESC

--What is the distribution of sold items across countries
SELECT 
c.country,
SUM(f.quantity) total_sold_items
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY c.country
ORDER BY total_sold_items DESC

--Total Sales by country 
Select
c.country,
SUM(f.sales_amount) total_sales
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY country
ORDER BY total_sales DESC

--Total Quantity by Category
Select 
P.category,
SUM(f.quantity)
From gold.fact_sales f
Left Join gold.dim_products p
on p.product_key = f.product_key
Group by category 

--AVG price by product
SELECT 
	p.product_id,
	p.product_name,
	AVG(f.price) avg_price
FROM gold.fact_sales f 
	LEFT JOIN gold.dim_products p
on p.product_key = f.product_key
GROUP BY 
	p.product_id,
	p.product_name
ORDER BY avg_price DESC

--Total orders by customers
SELECT 
    f.customer_key, 
    SUM(f.quantity) AS total_orders 
FROM 
    gold.fact_sales f
LEFT JOIN 
    gold.dim_customers c ON c.customer_key = f.customer_key
GROUP BY 
    f.customer_key
ORDER BY 
    total_orders DESC;   

